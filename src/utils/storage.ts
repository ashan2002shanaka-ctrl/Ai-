import { Conversation, AppSettings } from '../types';

const STORAGE_KEYS = {
  CONVERSATIONS: 'black_ghost_conversations_v1',
  ACTIVE_ID: 'black_ghost_active_id_v1',
  SETTINGS: 'black_ghost_settings_v1',
  SPLASH_SEEN: 'black_ghost_splash_seen_v1',
};

export const DEFAULT_SETTINGS: AppSettings = {
  model: 'gemini-3.8-flash',
  temperature: 0.7,
  systemInstruction: '',
  enableSearchGrounding: false,
  theme: 'black-ghost',
  speechVoice: 'Kore',
  streamResponses: true,
  userMemory: {
    userName: '',
    occupation: '',
    preferredTone: 'balanced',
    customPreferences: '',
    preferredLanguage: 'English',
  },
};

export function loadConversations(): Conversation[] {
  try {
    const raw = localStorage.getItem(STORAGE_KEYS.CONVERSATIONS);
    if (!raw) return [];
    const parsed = JSON.parse(raw);
    return Array.isArray(parsed) ? parsed : [];
  } catch (e) {
    console.error('Failed to load conversations from storage:', e);
    return [];
  }
}

export function saveConversations(conversations: Conversation[]): void {
  try {
    localStorage.setItem(STORAGE_KEYS.CONVERSATIONS, JSON.stringify(conversations));
  } catch (e) {
    console.error('Failed to save conversations to storage:', e);
  }
}

export function loadActiveId(): string | null {
  try {
    return localStorage.getItem(STORAGE_KEYS.ACTIVE_ID);
  } catch {
    return null;
  }
}

export function saveActiveId(id: string | null): void {
  try {
    if (id) {
      localStorage.setItem(STORAGE_KEYS.ACTIVE_ID, id);
    } else {
      localStorage.removeItem(STORAGE_KEYS.ACTIVE_ID);
    }
  } catch (e) {
    console.error('Failed to save active id:', e);
  }
}

export function loadSettings(): AppSettings {
  try {
    const raw = localStorage.getItem(STORAGE_KEYS.SETTINGS);
    if (!raw) return DEFAULT_SETTINGS;
    return { ...DEFAULT_SETTINGS, ...JSON.parse(raw) };
  } catch {
    return DEFAULT_SETTINGS;
  }
}

export function saveSettings(settings: AppSettings): void {
  try {
    localStorage.setItem(STORAGE_KEYS.SETTINGS, JSON.stringify(settings));
  } catch (e) {
    console.error('Failed to save settings:', e);
  }
}

export function exportAllData(): void {
  const conversations = loadConversations();
  const settings = loadSettings();
  const payload = {
    exportedAt: new Date().toISOString(),
    appName: 'BLACK GHOST AI',
    conversations,
    settings,
  };
  const blob = new Blob([JSON.stringify(payload, null, 2)], {
    type: 'application/json',
  });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `black-ghost-backup-${new Date().toISOString().slice(0, 10)}.json`;
  a.click();
  URL.revokeObjectURL(url);
}

export function exportConversationAsMarkdown(conversation: Conversation): void {
  let md = `# ${conversation.title}\n`;
  md += `*Generated by BLACK GHOST AI on ${new Date(conversation.createdAt).toLocaleString()}*\n\n---\n\n`;

  for (const msg of conversation.messages) {
    const sender = msg.role === 'user' ? '👤 User' : '👻 BLACK GHOST AI';
    md += `### ${sender} (${new Date(msg.timestamp).toLocaleTimeString()})\n\n`;
    if (msg.attachments && msg.attachments.length > 0) {
      md += `*Attached Files:* ${msg.attachments.map((a) => a.name).join(', ')}\n\n`;
    }
    md += `${msg.content}\n\n`;
    if (msg.groundingSources && msg.groundingSources.length > 0) {
      md += `**Sources:**\n`;
      msg.groundingSources.forEach((s) => {
        md += `- [${s.title}](${s.url})\n`;
      });
      md += `\n`;
    }
    md += `---\n\n`;
  }

  const blob = new Blob([md], { type: 'text/markdown' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `${conversation.title.replace(/[^a-zA-Z0-9_-]/g, '_')}.md`;
  a.click();
  URL.revokeObjectURL(url);
}
